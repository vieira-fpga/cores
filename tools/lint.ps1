<#
.SYNOPSIS
Checks our own SystemVerilog files with Verible.

.DESCRIPTION
Runs verible-verilog-format --verify and verible-verilog-lint
--rules_config_search on the .sv files that git tracks or would track. Skips
code we don't own, which upstream updates would overwrite:

- pocket/src/fpga/apf/, the openFPGA framework.
- Quartus-generated IP, found by its generator banner.
- Any folder below the root with its own LICENSE or COPYING file, such as a
  vendored module in modules/.

Exits with 1 if any file needs formatting or breaks a lint rule.

.PARAMETER Path
Files to check instead of every file in the repository. Skipped files stay
skipped.

.PARAMETER Fix
Format the files in place before linting.

.EXAMPLE
./tools/lint.ps1

.EXAMPLE
./tools/lint.ps1 -Path cores/rallyx/rtl/cpu.sv -Fix
#>
param(
    [string[]]$Path,
    [switch]$Fix
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Path $PSScriptRoot -Parent

# Returns true when a folder between the file and the root holds a license,
# which marks the folder as vendored code.
function Test-Vendored {
    param([string]$File)

    $dir = Split-Path -Path $File -Parent

    while ($dir.Length -gt $root.Length) {
        $licenses = Get-ChildItem -Path $dir -File |
            Where-Object { $_.BaseName -in @("LICENSE", "COPYING") }

        if ($licenses) {
            return $true
        }

        $dir = Split-Path -Path $dir -Parent
    }

    return $false
}

if ($Path) {
    $candidates = $Path | ForEach-Object { (Resolve-Path -Path $_).Path }
} else {
    $candidates = git -C $root ls-files --cached --others --exclude-standard -- "*.sv" |
        ForEach-Object { Join-Path -Path $root -ChildPath $_ }
}

$apf = Join-Path -Path $root -ChildPath "pocket/src/fpga/apf"
$files = @(
    $candidates | Where-Object {
        -not $_.StartsWith($apf) -and
        -not (Select-String -Path $_ -Pattern "WIZARD-GENERATED|Generated using ACDS" -Quiet) -and
        -not (Test-Vendored -File $_)
    }
)

if ($files.Count -eq 0) {
    Write-Host "SUMMARY PASS files=0"
    exit 0
}

if ($Fix) {
    verible-verilog-format --inplace @files
}

$failed = $false

verible-verilog-format --verify --inplace @files

if ($LASTEXITCODE -ne 0) {
    Write-Host "FAIL format: run ./tools/lint.ps1 -Fix to format the files listed above"
    $failed = $true
}

verible-verilog-lint --rules_config_search @files

if ($LASTEXITCODE -ne 0) {
    Write-Host "FAIL lint: see the rule violations above"
    $failed = $true
}

$status = if ($failed) { "FAIL" } else { "PASS" }
Write-Host "SUMMARY $status files=$($files.Count)"

if ($failed) {
    exit 1
}
